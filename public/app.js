const langButton = document.querySelector('.language-toggle');
const nav = document.querySelector('.nav');
const menu = document.querySelector('.menu-toggle');
let language = 'en';

function setLanguage(next) {
  language = next;
  document.documentElement.lang = next === 'en' ? 'en' : 'ko';
  document.title = next === 'en' ? 'INTRON GLOBAL | Global Trading & Distribution' : '인트론글로벌 | 무역·수출입·유통';
  document.querySelectorAll('[data-i18n]').forEach((node) => { node.innerHTML = copy[language][node.dataset.i18n]; });
  const labels = langButton.querySelectorAll('span');
  labels[0].classList.toggle('active', language === 'en');
  labels[2].classList.toggle('active', language === 'ko');
}

langButton.addEventListener('click', () => setLanguage(language === 'en' ? 'ko' : 'en'));
menu.addEventListener('click', () => { const open = nav.classList.toggle('open'); menu.setAttribute('aria-expanded', open); });
const closeMenu = () => { nav.classList.remove('open'); menu.setAttribute('aria-expanded', 'false'); };
nav.querySelectorAll('a').forEach((link) => link.addEventListener('click', closeMenu));
window.matchMedia('(min-width: 1101px)').addEventListener('change', closeMenu);
document.addEventListener('keydown', (event) => {
  if (event.key === 'Escape' && nav.classList.contains('open')) { closeMenu(); menu.focus(); }
});
document.getElementById('year').textContent = new Date().getFullYear();

